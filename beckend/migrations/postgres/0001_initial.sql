-- Preserve current logical types and nullability; this is not a data import.
-- UTC text dates retain compatibility with existing string comparisons/API data.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company TEXT, owner TEXT, whatsapp TEXT, email TEXT,
    category TEXT, logo TEXT, address TEXT, website TEXT,
    created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    plan TEXT NOT NULL CHECK (plan IN ('starter', 'pro', 'premium')),
    billing_cycle TEXT NOT NULL CHECK (billing_cycle IN ('monthly', 'quarterly', 'half_yearly', 'yearly')),
    currency TEXT NOT NULL DEFAULT 'USD',
    amount_usd BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    payment_reference TEXT,
    start_date TEXT,
    expiry_date TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    payment_verified BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_subscriptions_customer ON subscriptions(customer_id);
CREATE TABLE promo_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    subscription_id BIGINT NOT NULL,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX idx_promo_usage_customer_date ON promo_usage(customer_id, created_at);
